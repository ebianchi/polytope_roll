@dataclass
class TrajectoryOptimizationReport:
    costs: np.ndarray = None
    times: np.ndarray = None
    inputs: np.ndarray = None
    states: np.ndarray = None
    controls: np.ndarray = None


@dataclass
class TwoDTrajectoryOptimizationParams:
    sim_system: TwoDimensionalSystem = None
    traj_opt_dt: float = 0.1
    Q: np.ndarray = None
    R: np.ndarray = None
    S_base: np.ndarray = None
    half_freq: bool = False
    use_big_M: bool = False
    lookahead: int = 4
    horizon: int = 20
    use_receding_horizon: bool = False
    input_limit: float = 5.
    optimization_time_limit: float = None


class TwoDTrajectoryOptimization:
    """This class offers the capability of defining an initial state and a goal
    state, then it will perform offline trajectory optimization to generate a
    control sequence that will encourage the system to approach the goal state.

    Some cautionary notes:

        1. This expects the control inputs to be in the form [f_normal,
           f_tangent].  The location where this comes into play is in the
           optimization problem constraints in
           self._set_up_optimization_problem().

        2. This expects states to be in the same format as the LCS state
           vectors, namely [vx, vy, vth, x, y, th].

    Properties:
        params:         2D trajectory optimization parameters, including a
                        simulation system, a trajectory optimization time step
                        (coarser than the simulation system time step), the
                        matrices Q, R, and S_base, if the control frequency
                        should be halved or not, if the optimization problem
                        should use big M or not, and the number of lookahead
                        steps.
        lcs:            A TwoDSystemLCSApproximation object, constructed of a
                        system identical to self.params.sim_system except with a
                        coarser dt of self.params.traj_opt_dt.
        report:         A TrajectoryOptimizationReport that gets filled in with
                        statistics and results after the trajopt is performed.
        n_state:        The number of the state configuration (6 for 2D objects,
                        representing x, y, th prepended by their derivatives).
        n_contacts:     The number of contacts of the underlying polytope, i.e.
                        the number of polytope vertices.
        n_friction:     The number of friction polyhedron directions (2 for 2D
                        objects, representing +/-x).
        n_controls:     The number of control inputs of the underlying system.
    """
    params: TwoDTrajectoryOptimizationParams

    def __init__(self, params: TwoDTrajectoryOptimizationParams):
        # Construct an LCS of the simulation system using the coarser time step.
        self.lcs = self._construct_lcs(params.sim_system, params.traj_opt_dt)

        # Store some useful quantities, including the provided parameters.
        polytope = params.sim_system.params.polytope
        self.n_state = 2*polytope.n_config
        self.n_contacts = polytope.n_contacts
        self.n_friction = polytope.n_friction
        self.n_controls = params.R.shape[0]
        self.N = params.lookahead
        self.params = params

        # Initialize an empty report.
        self.report = None

    def _construct_lcs(self, sim_system, dt):
        """Given a system for simulation and a coarser time step, return an LCS
        for performing trajectory optimization on the simulation system.  The
        underlying system is identical to the simulation system except for its
        coarser time step."""

        # Make a(n unlinked) copy of the simulation system and edit the time
        # step.
        traj_opt_system = deepcopy(sim_system)
        traj_opt_system.params.dt = dt

        # Create an LCS approximation from the trajectory optimization system.
        lcs = TwoDSystemLCSApproximation(traj_opt_system)

        return lcs

    def run_trajectory_optimization(self, x_init, x_goal, loops: int = None):
        self.x_goal = x_goal
        if self.params.use_receding_horizon:
            assert loops is not None, f'Must provide loops if running ' + \
                f'receding horizon control.'
            print(f'Running receding-horizon MPC...')
            self._run_receding_horizon_mpc(x_init, loops)
        else:
            print(f'Running offline trajectory optimization...')
            self._run_offline_trajectory_optimization(x_init)

    def _run_receding_horizon_mpc(self, x_init, loops):
        """Given an initial state, a goal state, and a number of loops, perform
        receding horizon MPC."""

        # Keep track of the solved control inputs, costs, and loop times.
        inputs = np.zeros((0, self.n_controls))
        costs, times = np.array([]), np.array([])

        # Set the goal and initial states of the system.
        self.params.sim_system.set_initial_state(
            self.lcs._convert_lcs_state_to_system_state(x_init))

        # Set the running state to the current state.
        x_curr = x_init

        # Begin loop.
        for _ in range(loops):
            # Start timer.
            start_time = timeit.default_timer()

            # Build and solve the optimization problem model.
            self._update_lcs_plus_terms(x_curr)
            _xs, us, cost = self._set_up_and_solve_optimization_problem(x_curr)

            # Apply the controls on the simulation system.
            control_input = self._simulate_underlying_system_with_controls(us)

            # Get the latest state to use for the next linearization.
            sys_state = self.params.sim_system.state_history[-1, :]
            x_curr = self.lcs._convert_system_state_to_lcs_state(sys_state)

            # Save the control input and objective cost.
            inputs = np.vstack((inputs, control_input))
            costs = np.hstack((costs, cost))

            # Record the loop time.
            loop_time = timeit.default_timer() - start_time
            times = np.hstack((times, loop_time))

        # Store the statistics and results of the trajectory optimization in the
        # form of a report.
        report = TrajectoryOptimizationReport(costs=costs, times=times,
            inputs=inputs, states = self.params.sim_system.state_history,
            controls = self.params.sim_system.control_history)

        self.report = report

    def _run_offline_trajectory_optimization(self, x_init):
        """Given an initial state and a goal state, perform trajectory
        optimization iteratively until the LCS throughout the trajectory is
        linearized about the produced state trajectory."""

        def compute_trajectory_error(traj_1, traj_2):
            """Given two trajectories, compute the average error between them
            per timestep."""
            assert traj_1.shape == traj_2.shape == (self.N+1, self.n_state), \
                f'Expected shape ({self.N+1}, {self.n_state}), got ' + \
                f' {traj_1.shape} and {traj_2.shape}.'
            
            Q = self.params.Q
            
            traj_diff = traj_1 - traj_2
            total_error = 0
            for i in range(self.N+1):
                total_error += traj_diff[i] @ Q @ traj_diff[i]
            return total_error / (self.N+1)

        # Keep track of the solved control inputs, costs, and loop times.
        inputs = np.zeros((self.N, self.n_controls))
        costs, times = np.array([]), np.array([])

        # Use the initial state repeated as the first simulation trajectory and
        # the goal state repeated as the first plan trajectory.
        sim_states = np.tile(x_init, (self.N+1, 1))
        plan_states = np.tile(self.x_goal, (self.N+1, 1))

        # Compute the initial trajectory error.
        loops = 0
        traj_errors = np.array([
            compute_trajectory_error(sim_states, plan_states)])
        print(f'{loops} Trajectory error: {traj_errors[-1]}')
        
        # Make first plot.
        self.plot_trajectories(
            loop=loops, inputs=inputs, sim_states=sim_states, times=times,
            plan_states=plan_states, create=True
        )

        # Begin loop.
        while traj_errors[-1] > 1e-1:
            # Start timer.
            start_time = timeit.default_timer()
            loops += 1

            # Update the LCS terms based on the current set of inputs.
            self._construct_LCS_terms_from_inputs(inputs, x_init)

            # Build and solve the optimization problem model.
            xs, us, cost = self._set_up_and_solve_optimization_problem(x_init)

            # Store the results.
            inputs = us
            plan_states = xs
            sim_states = self.sim_traj

            # Compute the differences between the plan and simulation states.
            traj_error = compute_trajectory_error(sim_states, plan_states)
            print(f'{loops} Trajectory error: {traj_error}')

            # Save the objective cost and trajectory errors.
            costs = np.hstack((costs, cost))
            traj_errors = np.hstack((traj_errors, traj_error))

            # Record the loop time.
            loop_time = timeit.default_timer() - start_time
            times = np.hstack((times, loop_time))

            # Update the plot.
            self.plot_trajectories(
                loop=loops, inputs=inputs, sim_states=sim_states, times=times,
                plan_states=plan_states, create=False
            )

        # Store the statistics and results of the trajectory optimization in the
        # form of a report.
        report = TrajectoryOptimizationReport(costs=costs, times=times,
            inputs=inputs, states = self.params.sim_system.state_history,
            controls = self.params.sim_system.control_history)

        self.report = report

    def _construct_LCS_terms_from_inputs(self, inputs, x_init):
        """Using the provided inputs from a provided initial state, simulate a
        coarse system with the inputs to get a trajectory of states.  Use those
        states as the linearization knot points for the LCS terms."""
        # Check some shapes.
        assert inputs.shape == (self.N, self.n_controls), f'Expected shape ' \
            f'{(self.N, self.n_controls)}, got {inputs.shape}'
        assert x_init.shape == (self.n_state,), f'Expected shape ' \
            f'{(self.n_state,)}, got {x_init.shape}'

        # Simulate the coarse system to get the trajectory of states.
        self.lcs.simulate_dynamics_over_horizon(
            controls_over_horizon=inputs, init_state=x_init, roll_out_lcs=True)

        x_traj = self.lcs.state_history
        assert x_traj.shape == (self.N+1, self.n_state), f'Expected shape ' \
            f'{(self.N+1, self.n_state)}, got {x_traj.shape}'

        # Get the LCS terms from this state trajectory.
        self.As, self.Bs, self.Cs, self.ds, self.Gs, self.Hs, self.Js, \
            self.ls, self.Ps, self.Qs, self.Rs, self.Ss = \
            self.get_lcs_plus_terms_over_horizon(x_traj[:-1, :])
        print('Updated LCS terms from inputs.')

        # Store the simulation trajectory for plotting later.
        self.sim_traj = x_traj.copy()

    def _simulate_underlying_system_with_controls(self, us):
        """Given the control array from solving the optimization problem, use
        the first control input to apply to the real system, doing a zero-order
        hold with the trajectory optimization's output.  Return the control
        inputs used."""

        # For convenience...
        dt_traj_opt = self.params.traj_opt_dt
        dt_sim = self.params.sim_system.params.dt
        t_multiple = int(dt_traj_opt / dt_sim)
        mu_control = self.params.sim_system.params.mu_control

        # Clip the control input to enforce it is within feasible bounds (slight
        # infeasibility is possible due to numerics).
        control_input = us[0]
        control_input = np.clip(control_input,
                                [0, -mu_control*max(0, control_input[0])],
                                [np.inf, mu_control*max(0, control_input[0])])
        for _ in range(t_multiple):
            self.params.sim_system.step_dynamics(control_input)

        # If we want to apply control at half the frequency, then apply the
        # second solved control input too.
        if self.params.half_freq:
            inputs = np.vstack((inputs, control_input))

            control_input2 = us[1]
            control_input2 = np.clip(control_input2,
                                [0, -mu_control*max(0, control_input2[0])],
                                [np.inf, mu_control*max(0, control_input2[0])])
            for _ in range(t_multiple):
                self.params.sim_system.step_dynamics(control_input2)

            control_input = np.vstack((control_input, control_input2))

        return control_input

    def _update_lcs_plus_terms(self, x_current=None):
        """"""
        lookahead = self.params.lookahead

        # If doing receding horizon, use the current state and use its
        # linearization for the entire horizon.
        if self.params.use_receding_horizon:
            assert x_current is not None, 'Must provide a current state for' + \
                ' receding horizon control.'
            
            # Get the LCS terms for the current state, to be used for whole
            # horizon.
            A, B, C, d, G, H, J, l, P, Q, R, S = \
                self._get_lcs_plus_terms_at_state(x_current)
            self.As, self.Bs, self.Cs, self.ds, self.Gs, self.Hs, self.Js, \
            self.ls, self.Ps, self.Qs, self.Rs, self.Ss = \
                [A]*lookahead, [B]*lookahead, [C]*lookahead, [d]*lookahead, \
                [G]*lookahead, [H]*lookahead, [J]*lookahead, [l]*lookahead, \
                [P]*lookahead, [Q]*lookahead, [R]*lookahead, [S]*lookahead
            
        else:
            raise NotImplementedError

    def _get_lcs_plus_terms_at_state(self, x_current):
        """Given a current state, return all of the LCS and control vectors and
        matrices."""

        # For convenience, grab the number of contacts, control matrices, and
        # the polytope.
        nu = self.n_controls
        p = self.n_contacts
        polytope = self.params.sim_system.params.polytope

        # Get the Q, R, and S matrices from the parameters.
        Q = self.params.Q
        R = self.params.R
        S_base = self.params.S_base
        assert Q.ndim == 2 and Q.shape[0] == Q.shape[1], f'Expected square ' + \
            f'matrix for Q, got shape {Q.shape}'
        assert R.ndim == 2 and R.shape[0] == R.shape[1], f'Expected square ' + \
            f'matrix for R, got shape {R.shape}'
        assert S_base.ndim == 2 and S_base.shape[0] == S_base.shape[1], \
            f'Expected square matrix for S_base, got shape {S_base.shape}'

        # Set the LCS initial state and linearization point, both to the current
        # state.
        self.lcs.set_initial_state(x_current)
        v, q = x_current[:3], x_current[3:]
        controls = np.zeros((nu))
        self.lcs.set_linearization_point(q, v, controls)

        # Get the relevant LCS matrices.
        A, B, C, d, G, H, J, l, P = self.lcs.get_lcs_terms()

        # To build the V matrix, get the angle between the ground and the
        # pivoting vertex as well as the index of that vertex.
        theta_v, pivot_index = polytope.get_theta_v_and_pivot_index_from_theta(
                                                                        q[2])

        # The lever angle of the center of mass is the ground angle plus the
        # angle between the convex hull face and the line between the pivot and
        # the center of mass.
        lever_angle = theta_v + polytope.gammas[(pivot_index-1) % p]

        # The lever arm is the distance between the pivot and center of mass.
        radii, _ = polytope.get_vertex_radii_angles()
        lever_arm = radii[pivot_index]

        # Build the matrix V such that V @ x yields the "slip vector".
        V = np.array([[1., 0., lever_arm*np.sin(lever_angle), 0., 0., 0.],
                      [0., 1., -lever_arm*np.cos(lever_angle), 0., 0., 0.]])

        # Get S to penalize the amount of slip, when S is used as the norm of the
        # current state vector.
        S = V.T @ S_base @ V

        # Return all the LCS and control vectors/matrices.
        return A, B, C, d, G, H, J, l, P, Q, R, S

    def get_lcs_plus_terms_over_horizon(self, xs_over_horizon):
        """For xs_over_horizon as a (n_timesteps, n_state) array, return all the
        LCS and control vectors and matrices over the horizon.  All of these
        terms will be returned as lists of length n_timesteps, of same-sized
        numpy arrays.

        e.g. As will be [np.ndarray(n_state, n_state)] * n_timesteps."""
        As, Bs, Cs, ds, Gs, Hs, Js, ls, Ps = [], [], [], [], [], [], [], [], []
        Qs, Rs, Ss = [], [], []

        for x in xs_over_horizon:
            A, B, C, d, G, H, J, l, P, Q, R, S = self._get_lcs_plus_terms_at_state(x)
            As.append(A)
            Bs.append(B)
            Cs.append(C)
            ds.append(d)
            Gs.append(G)
            Hs.append(H)
            Js.append(J)
            ls.append(l)
            Ps.append(P)
            Qs.append(Q)
            Rs.append(R)
            Ss.append(S)

        return As, Bs, Cs, ds, Gs, Hs, Js, ls, Ps, Qs, Rs, Ss

    def _set_up_and_solve_optimization_problem(self, x_start):
        """Set up and solve a Gurobi optimization problem, returning the control
        inputs and objective cost."""

        # For convenience, get the state, contacts, friction, and control sizes,
        # the number of lookahead steps, control friction, and input limit.
        n = self.n_state
        p = self.n_contacts
        k = self.n_friction
        nu = self.n_controls
        lookahead = self.params.lookahead
        mu_control = self.params.sim_system.params.mu_control
        input_limit = self.params.input_limit

        # Create a new gurobi model.
        model = GurobiModelHelper.create_optimization_model(
            "traj_opt", verbose=False)

        # Create variables.
        xs = GurobiModelHelper.create_xs(model, lookahead=lookahead, n=n)
        us = GurobiModelHelper.create_us(model, lookahead=lookahead, nu=nu,
                                         input_limit=input_limit)
        lambdas = GurobiModelHelper.create_lambdas(model, lookahead=lookahead,
                                                   p=p, k=k)
        ys = GurobiModelHelper.create_ys(model, lookahead=lookahead, p=p, k=k)

        # Set objective:  penalize distance to goal, control input, and slip
        # measurement.
        model = GurobiModelHelper.set_objective(
            model, lookahead=lookahead, Q=self.Qs, R=self.Rs, S=self.Ss, us=us,
            xs=xs, x_goal=self.x_goal)

        # Build constraints.
        model = GurobiModelHelper.add_initial_condition_constr(
            model, xs=xs, x_current=x_start)
        model = GurobiModelHelper.add_dynamics_constr(
            model, lookahead=lookahead, xs=xs, us=us, lambdas=lambdas,
            A=self.As, B=self.Bs, P=self.Ps, C=self.Cs, d=self.ds)
        model = GurobiModelHelper.add_complementarity_constr(
            model, lookahead=lookahead, use_big_M=self.params.use_big_M, xs=xs,
            us=us, lambdas=lambdas, ys=ys, p=p, k=k)
        model = GurobiModelHelper.add_output_constr(
            model, lookahead=lookahead, xs=xs, us=us, lambdas=lambdas, ys=ys,
            G=self.Gs, H=self.Hs, P=self.Ps, J=self.Js, l=self.ls)
        model = GurobiModelHelper.add_friction_cone_constr(
            model, lookahead=lookahead, mu_control=mu_control, us=us)
        
        # Set time limit if desired.
        if self.params.optimization_time_limit is not None:
            model.Params.TimeLimit = self.params.optimization_time_limit

        # Solve the optimization problem, returning the control input and cost.
        try:
            model.optimize()
            print('Obj: %g' % model.ObjVal)
            return xs.X, us.X, model.ObjVal

        except gp.GurobiError as e:  print(f'Error code {e.errno}: {e}')
        except AttributeError:  print('Encountered an attribute error')
        pdb.set_trace()

    def plot_trajectories(self, inputs, sim_states, plan_states, times,
                          loop: int = 0, create: bool = False,
                          save: bool = True):
        x_goal = self.x_goal[3]
        y_goal = self.x_goal[4]
        th_goal = self.x_goal[5]

        sxs, sys, sths = sim_states[:, 3], sim_states[:, 4], sim_states[:, 5]
        pxs, pys, pths = plan_states[:, 3], plan_states[:, 4], plan_states[:, 5]
        uns, uts = inputs[:, 0], inputs[:, 1]

        if create:
            file_utils.clear_temp_dir()
            self.plot = {}

            plt.ion()
            self.fig = plt.figure(figsize=(9.16, 10.81))
            self.fig.suptitle(f'Iteration {loop}')

            self.ax1 = self.fig.add_subplot(321)
            self.plot['sxs'] = self.ax1.plot(sxs, label='Simulated')
            self.plot['pxs'] = self.ax1.plot(pxs, label='Planned')
            self.ax1.plot([0, self.N], [x_goal, x_goal], 'r--', label='Target')
            self.ax1.set_ylabel('Meters')
            self.ax1.set_title('X direction')
            self.ax1.legend()

            self.ax2 = self.fig.add_subplot(323)
            self.plot['sys'] = self.ax2.plot(sys)
            self.plot['pys'] = self.ax2.plot(pys)
            self.ax2.plot([0, self.N], [y_goal, y_goal], 'r--')
            self.ax2.set_ylabel('Meters')
            self.ax2.set_title('Y direction')

            self.ax3 = self.fig.add_subplot(325)
            self.plot['sths'] = self.ax3.plot(sths)
            self.plot['pths'] = self.ax3.plot(pths)
            self.ax3.plot([0, self.N], [th_goal, th_goal], 'r--')
            self.ax3.set_ylabel('Radians')
            self.ax3.set_title('Z rotation')

            self.ax4 = self.fig.add_subplot(322)
            self.plot['uns'] = self.ax4.plot(uns, label='un')
            self.ax4.set_ylabel('Newtons')
            self.ax4.set_title('Normal direction')

            self.ax5 = self.fig.add_subplot(324)
            self.plot['uts'] = self.ax5.plot(uts, label='ut')
            self.ax5.set_ylabel('Newtons')
            self.ax5.set_title('Tangential direction')

            self.ax6 = self.fig.add_subplot(326)
            self.plot['times'] = self.ax6.plot(times)
            self.ax6.set_ylabel('Seconds')
            self.ax6.set_title('Iteration times')
            self.ax6.set_yscale('log')
            if self.params.optimization_time_limit is not None:
                tlim = self.params.optimization_time_limit
                self.plot['time_limit'] = self.ax6.plot(
                    [0, 1], [tlim, tlim], 'r--', label='Limit')
                self.ax6.legend()

        else:
            self.fig.suptitle(f'Iteration {loop}')
            
            self.plot['sxs'][0].set_ydata(sxs)
            self.plot['pxs'][0].set_ydata(pxs)

            self.plot['sys'][0].set_ydata(sys)
            self.plot['pys'][0].set_ydata(pys)

            self.plot['sths'][0].set_ydata(sths)
