"""This file defines a class that does trajectory optimization.  This class can
be used for receding-horizon model predictive control or for offline full
trajectory optimization.  The trajectory optimzation formulates a mixed-integer
optimization problem of the form:

           min         sum_{k=0}^{N-1} (x_k-x_goal)^T Q (x_k-x_goal) \
    x_k, lambda_k, u_k                 + u_k^T R u_k + x_k^T S x_k

        such that   x_{k+1} = A x_k + B u_k + C lambda_k + d
                    M_1 s_k >= G x_k + H u_k + J lambda_k + l >= 0
                    M_2 (1 - s_k) >= lambda_k >= 0
                    sl_k = V x_K
                    s_k in {0, 1}^{p(k+2)}
                    x_0 = x(0)

...where the mixed integer portion is contained in the p*(k+2) vector of binary
variables, s_k.  The matrix S, when used as a norm on the current state vector,
penalizes any slip that is apparent in the state's velocity terms.  The scalars
M_1 and M_2 should be large numbers (used for the big M method).

Another option is the following (non-convex) formulation:

           min         sum_{k=0}^{N-1} (x_k-x_goal)^T Q (x_k-x_goal) \
    x_k, lambda_k, u_k                 + u_k^T R u_k + x_k^T S x_k

        such that   x_{k+1} = A x_k + B u_k + C lambda_k + d
                    y_k = G x_k + H u_k + J lambda_k + l >= 0
                    sl_k = V x_K
                    lambda_k >= 0
                    y_k @ lambda_k == 0        <-- complementarity (non-convex)
                    x_0 = x(0)

When used in receding horizon fashion, the first u_0 is applied to the system
and the state is updated.  The next optimization problem is solved with the
updated state as the initial condition, and the process repeats.

When used for offline trajectory optimization, the LCS is time-varying as well,
and the process is repeated until the LCS linearization points are within a
tolerance of the trajectory generated by the optimization problem."""

